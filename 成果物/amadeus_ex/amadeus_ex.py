"""アマデウス紅莉栖(amadeus_ex)のモーション定義。

このモデルには既存モーションが1つもないため、検証スクリプトは値域と
基本姿勢を既存カーブから推定できない。値域と初期値はモデル本体
(moc3)から読み取った値を使っている(編集用ファイルの値とも一致):

  ParamEyeROpen    0〜1   初期値1  名前は右目だが両目を同時に開閉する
  ParamEyeRSmile   0〜1   初期値0  両目。開き0と組み合わせると笑い目(^^)、
                                    開き1と組み合わせると目が丸く見開かれる
  ParamEyeBallX/Y -1〜1   初期値0  左右ははっきり動く。上下は控えめ
  ParamMouthOpenY  0〜1   初期値0  最大でも口は小さくしか開かない
  ParamMouthForm  -1〜1   初期値0  -1で口角が下がる(への字)、+1でうっすら笑顔
  Param6           0〜10  初期値0  考える腕。1.9で両手を前で組む、
                                    4以上であごに手を当てる。3.4付近は腕が
                                    宙に浮く途中形なので、そこでは止めない
  Param8           0〜1   初期値0  考え顔(むっとした「∩」の口)
  Param9           0〜1   初期値0  頬の赤み

物理演算の出力(直接動かさない): Param・Param2・Param3(まつ毛と瞳。
目の開閉から連動)、Param4・Param5(腕と髪。呼吸から連動)、
Param7(腕の揺れ。考える腕から連動)。ParamBreath は自動呼吸に任せる。

頭・体の角度や眉のパラメータが存在しないため、表現はすべて
目・視線・口・頬・考える腕の組み合わせで行う。
モーション再生中は自動まばたきが止まるので、長めのモーションには
まばたきを入れている。
"""


def define(curve, motion):
    MOTIONS = {}

    # ------------------------------------------------------------ 微笑み(感情)
    # 目を閉じた笑い目と、ほんのり赤い頬
    D = 3.0
    MOTIONS["kurisu_smile"] = motion(D, [
        curve("ParamEyeROpen", [(0, 1), (0.35, 0), (2.3, 0), (2.7, 1), (D, 1)]),
        curve("ParamEyeRSmile", [(0, 0), (0.35, 1), (2.3, 1), (2.7, 0), (D, 0)]),
        curve("ParamMouthForm", [(0, 0), (0.35, 1), (2.3, 1), (2.8, 0), (D, 0)]),
        curve("ParamMouthOpenY", [(0, 0), (0.4, 0.5), (1.2, 0.3), (2.2, 0.35), (2.7, 0), (D, 0)]),
        curve("Param9", [(0, 0), (0.5, 0.4), (2.3, 0.4), (2.9, 0), (D, 0)]),
    ])

    # ------------------------------------------------------------ 照れ隠し(感情)
    # 「べ、別に嬉しくなんか…」真っ赤になって目をそらし、前で手を組んでもじもじ
    D = 4.5
    MOTIONS["kurisu_embarrassed"] = motion(D, [
        curve("Param9", [(0, 0), (0.5, 1), (3.7, 1), (4.3, 0), (D, 0)]),
        curve("Param6", [(0, 0), (0.8, 1.9), (1.6, 1.7), (2.3, 1.9), (3.0, 1.7), (3.7, 1.9), (4.4, 0), (D, 0)]),
        curve("ParamEyeBallX", [(0, 0), (0.4, 0.8), (1.8, 0.8), (2.1, 0.2), (2.4, 0.8), (3.7, 0.8), (4.2, 0), (D, 0)]),
        curve("ParamEyeBallY", [(0, 0), (0.4, -0.5), (3.7, -0.5), (4.2, 0), (D, 0)]),
        curve("ParamEyeROpen", [(0, 1), (0.4, 0.7), (1.2, 0.7), (1.3, 0), (1.4, 0.7), (3.7, 0.7), (4.2, 1), (D, 1)]),
        curve("ParamMouthForm", [(0, 0), (0.4, -0.7), (3.7, -0.7), (4.2, 0), (D, 0)]),
        curve("ParamMouthOpenY", [(0, 0), (0.5, 0.2), (1.0, 0.4), (1.3, 0.1), (1.6, 0.3), (2.0, 0), (D, 0)]),
    ])

    # ------------------------------------------------------------ びっくり(リアクション)
    # 一瞬まばたきしてから目を丸く見開き(開き1+笑い1で見開きになる)、口を開ける
    D = 2.5
    MOTIONS["kurisu_surprised"] = motion(D, [
        curve("ParamEyeROpen", [(0, 1), (0.08, 0.2), (0.2, 1), (D, 1)]),
        curve("ParamEyeRSmile", [(0, 0), (0.08, 0), (0.2, 1), (1.5, 1), (2.1, 0), (D, 0)]),
        curve("ParamEyeBallY", [(0, 0), (0.2, 0.3), (1.5, 0.3), (2.1, 0), (D, 0)]),
        curve("ParamMouthOpenY", [(0, 0), (0.2, 1), (1.4, 0.9), (2.1, 0), (D, 0)]),
        curve("ParamMouthForm", [(0, 0), (0.2, -0.5), (1.4, -0.5), (2.1, 0), (D, 0)]),
    ])

    # ------------------------------------------------------------ ジト目(リアクション)
    # 呆れた半目で視線をそらし、横目でちらっと戻す。口はへの字
    D = 4.0
    MOTIONS["kurisu_jitome"] = motion(D, [
        curve("ParamEyeROpen", [(0, 1), (0.4, 0.5), (1.9, 0.5), (2.0, 0), (2.1, 0.5), (3.3, 0.5), (3.8, 1), (D, 1)]),
        curve("ParamEyeBallX", [(0, 0), (0.4, 0), (1.0, -0.9), (2.2, -0.9), (2.6, 0), (3.3, 0), (D, 0)]),
        curve("ParamEyeBallY", [(0, 0), (0.4, -0.2), (3.3, -0.2), (3.8, 0), (D, 0)]),
        curve("ParamMouthForm", [(0, 0), (0.4, -1), (3.3, -1), (3.8, 0), (D, 0)]),
        curve("ParamMouthOpenY", [(0, 0), (2.6, 0), (2.8, 0.3), (3.1, 0), (D, 0)]),
    ])

    # ------------------------------------------------------------ きょろきょろ(待機)
    # 左、右、上と視線を送る。途中でまばたき
    D = 4.0
    MOTIONS["kurisu_lookaround"] = motion(D, [
        curve("ParamEyeBallX", [(0, 0), (0.4, -0.9), (1.2, -0.9), (1.6, 0.9), (2.4, 0.9), (2.8, 0), (3.6, 0), (D, 0)]),
        curve("ParamEyeBallY", [(0, 0), (1.2, 0), (1.6, 0.1), (2.4, 0.1), (2.8, 0.8), (3.4, 0.8), (3.8, 0), (D, 0)]),
        curve("ParamEyeROpen", [(0, 1), (1.3, 1), (1.4, 0), (1.5, 1), (D, 1)]),
        curve("ParamMouthForm", [(0, 0), (0.4, -0.2), (3.4, -0.2), (3.8, 0), (D, 0)]),
    ])

    # ------------------------------------------------------------ うとうと(待機)
    # まぶたが重くなり、あくび、はっと目を覚ます
    D = 5.0
    MOTIONS["kurisu_sleepy"] = motion(D, [
        curve("ParamEyeROpen", [(0, 1), (1.0, 0.45), (1.5, 0.55), (2.4, 0.1), (2.9, 0.1),
                                (3.8, 0.1), (3.95, 1), (D, 1)]),
        curve("ParamEyeRSmile", [(0, 0), (3.8, 0), (3.95, 0.6), (4.5, 0), (D, 0)]),
        curve("ParamEyeBallY", [(0, 0), (1.0, -0.4), (3.8, -0.4), (3.95, 0), (D, 0)]),
        curve("ParamMouthOpenY", [(0, 0), (1.5, 0), (2.2, 1), (2.9, 1), (3.4, 0), (D, 0)]),
        curve("ParamMouthForm", [(0, 0), (1.5, 0), (2.2, -0.6), (2.9, -0.6), (3.4, 0), (D, 0)]),
    ])

    # ------------------------------------------------------------ 考え中(仕草)
    # あごに手を当て、むっとした考え顔で視線は斜め上
    D = 4.5
    MOTIONS["kurisu_thinking"] = motion(D, [
        curve("Param6", [(0, 0), (1.2, 10), (3.4, 10), (D, 0)]),
        curve("Param8", [(0, 0), (0.9, 1), (3.4, 1), (4.2, 0), (D, 0)]),
        curve("ParamEyeBallX", [(0, 0), (0.9, -0.6), (2.2, -0.7), (2.6, -0.3), (3.4, -0.6), (4.1, 0), (D, 0)]),
        curve("ParamEyeBallY", [(0, 0), (0.9, 0.7), (3.4, 0.7), (4.1, 0), (D, 0)]),
        curve("ParamEyeROpen", [(0, 1), (0.9, 0.75), (2.3, 0.75), (2.4, 0), (2.5, 0.75), (3.4, 0.75), (4.1, 1), (D, 1)]),
    ])

    # model3.json の Action グループへ登録する内容
    # (WebUIに表示する名前、フェードイン秒、フェードアウト秒)
    MANIFEST = [
        ("kurisu_smile", "微笑み", 0.4, 0.5),
        ("kurisu_embarrassed", "照れ隠し", 0.4, 0.5),
        ("kurisu_surprised", "びっくり", 0.2, 0.5),
        ("kurisu_jitome", "ジト目", 0.4, 0.5),
        ("kurisu_lookaround", "きょろきょろ", 0.4, 0.5),
        ("kurisu_sleepy", "うとうと", 0.5, 0.5),
        ("kurisu_thinking", "考え中", 0.5, 0.5),
    ]
    return MOTIONS, MANIFEST
